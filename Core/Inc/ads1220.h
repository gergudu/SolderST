/**
 ******************************************************************************
 * @file    ads1220.h
 * @brief   Драйвер ADS1220 — 24-bit SPI ADC для измерения RTD паяльника.
 *
 * Схема подключения (подтверждено, совпадает с REG0/REG3 побитово):
 *   Ток IDAC1 (1000 мкА) течёт: AIN3/REFN1 → RTD → Rref(100 Ом) → GND
 *   RTD  измеряется дифференциально: AIN1(+) / AIN0(-)
 *        (AIN1 — тот же узел, что AIN3/REFN1, верх цепи;
 *         AIN0 — средняя точка RTD/Rref, тот же узел, что REFP0)
 *   Rref измеряется дифференциально: REFP0(+) / REFN0(-)
 *        (REFP0 — средняя точка RTD/Rref, тот же узел, что AIN0;
 *         REFN0 — GND, ratiometric-опора)
 *   CS_Solder   → PB8 (SPI2_CS1)
 *   CS_Desolder → PB9 (SPI2_CS1)
 *
 * Оба канала (паяльник/отсос) — раздельные чипы ADS1220 с одинаковой
 * топологией AIN0/AIN1/AIN3 каждый на своих ногах (REG0/REG3
 * идентичны для обоих, общая init_chip()).
 *
 * RTD паяльника: R = 21.7 + T * 0.072 Ом
 * Калибровка смещения проводов (~0.25 Ом) — через biasSolder в config.
 ******************************************************************************
 */

#ifndef INC_ADS1220_H_
#define INC_ADS1220_H_

#include "main.h"
#include "spi.h"
#include <stdint.h>
#include <stdbool.h>

/* --------------------------------------------------------------------------
 * Параметры измерительной схемы
 * -------------------------------------------------------------------------- */
#define ADS1220_RREF_OHM        1000.0f   /* Опорный резистор, Ом           */
#define ADS1220_IDAC_UA         500       /* Ток возбуждения IDAC1, мкА     */
#define ADS1220_PGA_GAIN        16.0f      /* Коэффициент PGA                */

/* --------------------------------------------------------------------------
 * Команды SPI
 * -------------------------------------------------------------------------- */
#define ADS1220_CMD_RESET       0x06
#define ADS1220_CMD_START       0x08
#define ADS1220_CMD_POWERDOWN   0x02
#define ADS1220_CMD_RDATA       0x10
#define ADS1220_CMD_RREG(r)     (0x20 | ((r) << 2))  /* Читать регистр r      */
#define ADS1220_CMD_WREG(r)     (0x40 | ((r) << 2))  /* Писать регистр r      */

/* --------------------------------------------------------------------------
 * Регистры (адреса 0..3)
 * -------------------------------------------------------------------------- */
/* REG0: MUX[7:4] GAIN[3:1] PGA_BYPASS[0] */
#define ADS1220_REG0_MUX_AIN0_AIN1  (0x00 << 4)  /* AIN0(+)/AIN1(-) */
#define ADS1220_REG0_GAIN_1         (0x00 << 1)  /* PGA gain = 1    */
#define ADS1220_REG0_PGA_BYPASS_OFF (0x00)        /* PGA включён     */

/* REG1: DR[7:5] MODE[4:3] CM[2] TS[1] BCS[0] */
#define ADS1220_REG1_DR_20SPS       (0x00 << 5)  /* 20 SPS           */
#define ADS1220_REG1_MODE_NORMAL    (0x00 << 3)  /* Normal mode      */
#define ADS1220_REG1_CM_CONTINUOUS  (0x01 << 2)  /* Continuous conv  */
#define ADS1220_REG1_TS_OFF         (0x00 << 1)
#define ADS1220_REG1_BCS_OFF        (0x00)

/* REG2: VREF[7:6] 50/60[5:4] PSW[3] IDAC[2:0] */
#define ADS1220_REG2_VREF_REFP0     (0x02 << 6)  /* Внешняя опора REFP0/REFN0 */
#define ADS1220_REG2_FIR_OFF        (0x00 << 4)
#define ADS1220_REG2_PSW_OFF        (0x00 << 3)
#define ADS1220_REG2_IDAC_500UA     (0x05) /* IDAC = 500 мкА */

/* REG3: I1MUX[7:5] I2MUX[4:2] DRDYM[1] RESERVED[0] */
#define ADS1220_REG3_IDAC1_AIN3_REFN1   (0x04 << 5) /* IDAC1 → AIN3 / REFN1 */
#define ADS1220_REG3_IDAC2_OFF      (0x00 << 2)  /* IDAC2 выкл    */
#define ADS1220_REG3_DRDYM_DOUT     (0x00 << 1)  /* DRDY на DOUT  */

/* ADS1220_DRDY_TIMEOUT_MS удалён — не использовался нигде (ни в
   старой блокирующей версии на HAL_Delay, ни в новой на HAL_GetTick):
   DRDY не разведён отдельным пином, см. README. */

/* --------------------------------------------------------------------------
 * Публичный API
 * -------------------------------------------------------------------------- */

/**
 * @brief  Инициализация ADS1220 (раздельно для каждого канала):
 *         сброс, конфигурация регистров, старт.
 * @retval true  — успешно
 * @retval false — ошибка SPI или чип не отвечает
 */
bool ADS1220_InitSolder(void);
bool ADS1220_InitDesolder(void);

/**
 * @brief  Получить температуру паяльника в °C. Неблокирующее — если с
 *         последнего чтения прошло меньше периода преобразования
 *         (~55 мс), возвращает false сразу, без ожидания.
 *         Вычисление: R_rtd = raw/FS * Rref  →  T = (R_rtd - R0) / coeff
 * @param  out_temp_c — указатель для результата
 * @retval true  — успешно, новые данные записаны в out_temp_c
 * @retval false — ещё не время следующего чтения, либо ошибка SPI
 */
bool ADS1220_ReadTempSolder(float *out_temp_c);

/**
 * @brief Измерение температуры отсоса — отдельный чип ADS1220 (CS_Desolder).
 *        Топология идентична паяльнику (AIN1(+)/AIN0(-), IDAC1→AIN3/REFN1,
 *        REFP0/REFN0) — подтверждено, оба чипа одинаково разведены на
 *        своих собственных ногах AIN0-AIN3, поэтому REG0_VAL общий для
 *        обоих каналов (init_chip() одна на двоих).
 *        Неблокирующее: если с последнего чтения прошло меньше периода
 *        преобразования (~55 мс), возвращает false без задержки —
 *        значит, новых данных ещё нет, старое значение остаётся в силе.
 */
bool ADS1220_ReadTempDesolder(float *out_temp_c);


#endif /* INC_ADS1220_H_ */
